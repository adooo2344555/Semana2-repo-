
number = int(input("Ingrese un número del 1 al 7: "))

if number == 1:
    print("Lunes")
elif number == 2:
    print("Martes")
elif number == 3:
    print("Miércoles")
elif number == 4:
    print("Jueves")
elif number == 5:
    print("Viernes")
elif number == 6:
    print("Sábado")
elif number == 7:
    print("Domingo")
else:
    print("Error: número fuera de rango")